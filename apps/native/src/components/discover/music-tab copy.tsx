import {
  Heart,
  Pause,
  Play,
  Radio,
  SkipForward,
  Volume2,
  VolumeX,
} from "@tamagui/lucide-icons";
import { LinearGradient } from "expo-linear-gradient";
import { useEffect, useRef, useState } from "react";
import {
  Animated,
  Dimensions,
  FlatList,
  Image,
  ScrollView,
  StyleSheet,
  Text,
  TouchableOpacity,
  View,
} from "react-native";
import AudioPlayer from "react-native-feed-media-audio-player/lib/audio-player";

const { width } = Dimensions.get("window");

type PlayerAvailability = boolean | null;

interface Station {
  id: number;
  name: string;
  options?: {
    background_image_url?: string;
    image?: string;
    subheader?: string;
  };
  can_skip?: boolean;
  can_like?: boolean;
}

interface CurrentPlay {
  title: string;
  artist: string;
  album: string;
  duration: number;
  metadata?: {
    background_image_url?: string;
    image?: string;
    artwork?: string;
  };
  canSkip?: boolean;
}

const player = new AudioPlayer({ debug: true });
player.initialize(
  "demo",
  "demo",
  (available) => {
    // Auto-initialization logic remains the same
  },
  true
);

export const MusicTab = () => {
  const [playbackState, setPlaybackState] =
    useState<AudioPlayer["playbackState"]>();
  const [available, setAvailable] = useState<PlayerAvailability>(null);
  const [requestingSkip, setRequestingSkip] = useState<boolean>(false);
  const [stations, setStations] = useState<Station[]>([]);
  const [activeStation, setActiveStation] = useState<Station | null>(null);
  const [currentPlay, setCurrentPlay] = useState<CurrentPlay | null>(null);
  const [elapsedTime, setElapsedTime] = useState<number>(0);
  const scrollX = useRef(new Animated.Value(0)).current;

  let elapsedTimer: number;

  // Format time function
  const formatTime = (seconds: number) => {
    const min = Math.floor(seconds / 60);
    const sec = Math.floor(seconds % 60);
    return `${min}:${sec < 10 ? "0" + sec : sec}`;
  };

  useEffect(() => {
    player.whenAvailable((available) => {
      if (!available) {
        setAvailable(false);
        return;
      }

      player.enableiOSAudioSession(true);
      setAvailable(true);
      setPlaybackState(player.playbackState);

      // Set stations from player
      if (player._stations && player._stations.length > 0) {
        setStations(player._stations);
        setActiveStation(player._activeStation || player._stations[0]);
      }

      // Set current play if available
      if (player._currentPlay) {
        setCurrentPlay(player._currentPlay);
      }

      // Update elapsed time at regular intervals
      elapsedTimer = window.setInterval(() => {
        if (playbackState === "PLAYING" && player._elapsedPlayTime) {
          setElapsedTime(player._elapsedPlayTime);
        }
      }, 1000);

      // Event bindings
      const stateChangeUnbind = player.on("state-change", (state) => {
        setPlaybackState(state);
      });

      const stationChangeUnbind = player.on("station-change", (station) => {
        setActiveStation(station);
      });

      const playStartedUnbind = player.on("play-started", (play) => {
        setRequestingSkip(false);
        setCurrentPlay(play);
        setElapsedTime(0);
      });

      const skipFailedUnbind = player.on("skip-failed", () => {
        setRequestingSkip(false);
      });

      const sessionUpdatedUnbind = player.on("session-updated", () => {
        setStations(player._stations);
      });

      return () => {
        stateChangeUnbind();
        stationChangeUnbind();
        playStartedUnbind();
        skipFailedUnbind();
        sessionUpdatedUnbind();
        clearInterval(elapsedTimer);
      };
    });
  }, []);

  const skip = () => {
    if (currentPlay?.canSkip !== false) {
      setRequestingSkip(true);
      player.skip();
    }
  };

  const handleStationSelect = (station: Station) => {
    player.activeStation = station;
    setActiveStation(station);
  };

  const renderStationItem = ({ item }: { item: Station }) => (
    <TouchableOpacity
      onPress={() => handleStationSelect(item)}
      style={[
        styles.stationItem,
        activeStation?.id === item.id && styles.stationItemSelected,
      ]}
    >
      <Radio
        color={activeStation?.id === item.id ? "#ffffff" : "#5D3FD3"}
        size={16}
      />
      <Text
        style={[
          styles.stationText,
          activeStation?.id === item.id && styles.stationTextSelected,
        ]}
      >
        {item.name}
      </Text>
    </TouchableOpacity>
  );

  const getStationImage = (station: Station | null) => {
    if (!station) return;

    return (
      station.options?.background_image_url ||
      station.options?.image ||
      "https://placehold.co/600x400/5D3FD3/ffffff?text=Music"
    );
  };

  const getTrackImage = () => {
    if (!currentPlay) return;

    return (
      currentPlay.metadata?.background_image_url ||
      currentPlay.metadata?.image ||
      currentPlay.metadata?.artwork ||
      getStationImage(activeStation) ||
      "https://placehold.co/600x400/5D3FD3/ffffff?text=Track"
    );
  };

  const renderNowPlaying = () => {
    if (!currentPlay) return null;

    const progressPercent = (elapsedTime / currentPlay.duration) * 100 || 0;

    return (
      <View style={styles.nowPlayingContainer}>
        <LinearGradient
          colors={["rgba(93, 63, 211, 0.8)", "rgba(93, 63, 211, 0.4)"]}
          style={styles.nowPlayingGradient}
        >
          <View style={styles.nowPlaying}>
            <Image
              source={{ uri: getTrackImage() }}
              style={styles.nowPlayingImage}
            />
            <View style={styles.nowPlayingContent}>
              <View style={styles.nowPlayingInfo}>
                <Text numberOfLines={1} style={styles.nowPlayingTitle}>
                  {currentPlay.title}
                </Text>
                <Text numberOfLines={1} style={styles.nowPlayingArtist}>
                  {currentPlay.artist}
                </Text>
              </View>

              <View style={styles.progressBarContainer}>
                <View style={styles.progressBarBackground}>
                  <View
                    style={[
                      styles.progressBar,
                      { width: `${progressPercent}%` },
                    ]}
                  />
                </View>
                <View style={styles.timeInfo}>
                  <Text style={styles.timeText}>{formatTime(elapsedTime)}</Text>
                  <Text style={styles.timeText}>
                    {formatTime(currentPlay.duration)}
                  </Text>
                </View>
              </View>

              <View style={styles.controls}>
                <TouchableOpacity
                  onPress={() => (player.volume = player.volume > 0 ? 0 : 1)}
                  style={styles.controlButton}
                >
                  {player.volume === 0 ? (
                    <VolumeX color="white" size={20} />
                  ) : (
                    <Volume2 color="white" size={20} />
                  )}
                </TouchableOpacity>

                <TouchableOpacity
                  onPress={() =>
                    playbackState === "PLAYING" ? player.pause() : player.play()
                  }
                  style={styles.playButton}
                >
                  {playbackState === "PLAYING" ? (
                    <Pause color="white" size={24} />
                  ) : (
                    <Play color="white" size={24} />
                  )}
                </TouchableOpacity>

                <TouchableOpacity
                  disabled={!currentPlay.canSkip || requestingSkip}
                  onPress={skip}
                  style={[
                    styles.controlButton,
                    (!currentPlay.canSkip || requestingSkip) &&
                      styles.disabledButton,
                  ]}
                >
                  <SkipForward
                    color={
                      !currentPlay.canSkip || requestingSkip
                        ? "#cccccc"
                        : "white"
                    }
                    size={20}
                  />
                </TouchableOpacity>
              </View>
            </View>
          </View>
        </LinearGradient>
      </View>
    );
  };

  const renderStationInfo = () => {
    if (!activeStation) return null;

    return (
      <View style={styles.stationInfoContainer}>
        <Image
          source={{ uri: getStationImage(activeStation) }}
          style={styles.stationImage}
        />
        <View style={styles.stationDetails}>
          <Text style={styles.stationTitle}>{activeStation.name}</Text>
          {activeStation.options?.subheader && (
            <Text style={styles.stationSubheader}>
              {activeStation.options.subheader}
            </Text>
          )}
          <View style={styles.stationFeatures}>
            {activeStation.can_skip && (
              <View style={styles.featureTag}>
                <SkipForward color="#5D3FD3" size={14} />
                <Text style={styles.featureText}>Skippable</Text>
              </View>
            )}
            {activeStation.can_like && (
              <View style={styles.featureTag}>
                <Heart color="#5D3FD3" size={14} />
                <Text style={styles.featureText}>Likeable</Text>
              </View>
            )}
          </View>
          <TouchableOpacity
            onPress={() => player.play()}
            style={styles.playStationButton}
          >
            <Play color="#ffffff" size={18} />
            <Text style={styles.playStationText}>Play Station</Text>
          </TouchableOpacity>
        </View>
      </View>
    );
  };

  if (available === null) {
    return (
      <View style={styles.loadingContainer}>
        <Text style={styles.loadingText}>Loading music...</Text>
      </View>
    );
  }

  if (available === false) {
    return (
      <View style={styles.errorContainer}>
        <Text style={styles.errorText}>
          Sorry, music is not available right now
        </Text>
      </View>
    );
  }

  return (
    <View style={styles.container}>
      {/* Stations Horizontal Scroll */}
      <View style={styles.stationsContainer}>
        <Text style={styles.sectionTitle}>Stations</Text>
        <FlatList
          contentContainerStyle={styles.stationsList}
          data={stations}
          horizontal
          keyExtractor={(item) => item.id.toString()}
          renderItem={renderStationItem}
          showsHorizontalScrollIndicator={false}
        />
      </View>

      {/* Active Station Info */}
      <ScrollView
        showsVerticalScrollIndicator={false}
        style={styles.contentContainer}
      >
        {renderStationInfo()}

        {/* Current Play Section */}
        {currentPlay && (
          <View style={styles.currentlyPlayingContainer}>
            <Text style={styles.sectionTitle}>Now Playing</Text>
            <View style={styles.currentlyPlayingCard}>
              <Image
                source={{ uri: getTrackImage() }}
                style={styles.currentlyPlayingImage}
              />
              <Text style={styles.currentlyPlayingTitle}>
                {currentPlay.title}
              </Text>
              <Text style={styles.currentlyPlayingArtist}>
                {currentPlay.artist}
              </Text>
              <Text style={styles.currentlyPlayingAlbum}>
                {currentPlay.album}
              </Text>

              {/* Player actions */}
              <View style={styles.currentlyPlayingActions}>
                <TouchableOpacity
                  onPress={() =>
                    playbackState === "PLAYING" ? player.pause() : player.play()
                  }
                  style={styles.actionButton}
                >
                  {playbackState === "PLAYING" ? (
                    <>
                      <Pause color="#5D3FD3" size={20} />
                      <Text style={styles.actionText}>Pause</Text>
                    </>
                  ) : (
                    <>
                      <Play color="#5D3FD3" size={20} />
                      <Text style={styles.actionText}>Play</Text>
                    </>
                  )}
                </TouchableOpacity>

                {activeStation?.can_skip && currentPlay.canSkip && (
                  <TouchableOpacity
                    disabled={requestingSkip}
                    onPress={skip}
                    style={[
                      styles.actionButton,
                      requestingSkip && styles.disabledActionButton,
                    ]}
                  >
                    <SkipForward
                      color={requestingSkip ? "#cccccc" : "#5D3FD3"}
                      size={20}
                    />
                    <Text
                      style={[
                        styles.actionText,
                        requestingSkip && styles.disabledActionText,
                      ]}
                    >
                      {requestingSkip ? "Skipping..." : "Skip"}
                    </Text>
                  </TouchableOpacity>
                )}

                {activeStation?.can_like && (
                  <TouchableOpacity style={styles.actionButton}>
                    <Heart color="#5D3FD3" size={20} />
                    <Text style={styles.actionText}>Like</Text>
                  </TouchableOpacity>
                )}
              </View>
            </View>
          </View>
        )}

        {/* Client ID Info */}
        <View style={styles.clientIdContainer}>
          <Text style={styles.clientIdLabel}>Client ID:</Text>
          <Text style={styles.clientIdText}>{player._clientID}</Text>
        </View>
      </ScrollView>

      {/* Bottom Player Bar */}
      {renderNowPlaying()}
    </View>
  );
};


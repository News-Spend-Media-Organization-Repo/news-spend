import type { MigrateDownArgs, MigrateUpArgs } from "@payloadcms/db-postgres";
import { sql } from "@payloadcms/db-postgres";

/**
 * Lets `news_analytics` recognise an event it has already stored, and records
 * when the server received each one.
 *
 * - `event_id`: minted by the app per event and reused on every retry. With
 *   `device_id` it forms a unique key, so a batch whose reply was lost, and is
 *   therefore sent again, counts once. Nullable, and NULLs never collide, so
 *   rows from app builds that do not send one are stored as before.
 * - `received_at`: server arrival time, kept apart from `timestamp` (the
 *   device's claim, now clamped). Nullable and not backfilled: inventing an
 *   arrival time for old rows would put a made-up value where an honest gap is
 *   better.
 *
 * Additive only and safe on a live table: two nullable columns, one index. The
 * table is small enough (a few MB) that the index build does not hold writes
 * for a noticeable time. Generated by `payload migrate:create`.
 */
export async function up({ db }: MigrateUpArgs): Promise<void> {
  await db.execute(sql`
    ALTER TABLE "news_analytics" ADD COLUMN "event_id" varchar;
    ALTER TABLE "news_analytics" ADD COLUMN "received_at" timestamp(3) with time zone;
    CREATE UNIQUE INDEX "deviceId_eventId_idx" ON "news_analytics" USING btree ("device_id","event_id");
  `);
}

export async function down({ db }: MigrateDownArgs): Promise<void> {
  await db.execute(sql`
    DROP INDEX "deviceId_eventId_idx";
    ALTER TABLE "news_analytics" DROP COLUMN "event_id";
    ALTER TABLE "news_analytics" DROP COLUMN "received_at";
  `);
}
